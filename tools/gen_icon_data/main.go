// gen_icon_data 将 tray/*.png 图标生成为 tray/icon_data.go 里的 base64 常量。
// 用生成代码代替 //go:embed，以规避个别环境的 gc 编译器对 embed 指令的兼容问题。
// 用法: 在仓库根目录执行 go run ./tools/gen_icon_data
package main

import (
	"encoding/base64"
	"fmt"
	"os"
	"strings"
)

func b64Const(name, file string) string {
	b, err := os.ReadFile(file)
	if err != nil {
		panic(err)
	}
	s := base64.StdEncoding.EncodeToString(b)
	var parts []string
	for len(s) > 120 {
		parts = append(parts, "\t\""+s[:120]+"\" +")
		s = s[120:]
	}
	parts = append(parts, "\t\""+s+"\"")
	return fmt.Sprintf("const %sB64 = \"\" +\n%s\n", name, strings.Join(parts, "\n"))
}

func main() {
	color := b64Const("iconColor", "tray/icon.png")
	tmpl := b64Const("iconTemplate", "tray/icon-template.png")
	out := "// Code generated by tools/gen_icon_data; DO NOT EDIT.\n\npackage main\n\nimport \"encoding/base64\"\n\n" +
		color + "\n" + tmpl + `
func mustDecode(s string) []byte {
	b, err := base64.StdEncoding.DecodeString(s)
	if err != nil {
		panic(err)
	}
	return b
}

var (
	iconColor    = mustDecode(iconColorB64)
	iconTemplate = mustDecode(iconTemplateB64)
)
`
	if err := os.WriteFile("tray/icon_data.go", []byte(out), 0o644); err != nil {
		panic(err)
	}
	fmt.Println("written tray/icon_data.go")
}
